create schema if not exists private;

alter table public.usuarios
  add column if not exists mobile_permissions jsonb not null default '{}'::jsonb;

create table if not exists public.mobile_devices (
  id uuid primary key default gen_random_uuid(),
  tenant text not null,
  user_id uuid not null,
  name text,
  platform text,
  app_version text,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  unique (tenant, id)
);

create table if not exists public.mobile_operations (
  id bigint generated by default as identity primary key,
  tenant text not null,
  operation_id text not null,
  device_id uuid not null,
  user_id uuid not null,
  entity_type text not null,
  entity_id text not null,
  operation_kind text not null,
  base_version bigint,
  payload jsonb not null default '{}'::jsonb,
  result jsonb not null,
  device_created_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (tenant, operation_id),
  foreign key (tenant, device_id) references public.mobile_devices(tenant, id)
);

create table if not exists public.mobile_audit_events (
  id bigint generated by default as identity primary key,
  tenant text not null,
  user_id uuid not null,
  device_id uuid,
  operation_id text,
  entity_type text not null,
  entity_id text not null,
  action text not null,
  server_version bigint not null default 1,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.mobile_attachments (
  id uuid primary key default gen_random_uuid(),
  tenant text not null,
  user_id uuid not null,
  device_id uuid not null,
  entity_type text not null,
  entity_id text not null,
  storage_path text not null,
  mime_type text,
  size_bytes bigint,
  sha256 text,
  status text not null default 'pending',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (tenant, storage_path),
  foreign key (tenant, device_id) references public.mobile_devices(tenant, id)
);

create index if not exists mobile_devices_user_idx
  on public.mobile_devices (tenant, user_id, enabled);
create index if not exists mobile_operations_sync_idx
  on public.mobile_operations (tenant, updated_at, id);
create index if not exists mobile_operations_user_idx
  on public.mobile_operations (tenant, user_id, created_at desc);
create index if not exists mobile_audit_events_sync_idx
  on public.mobile_audit_events (tenant, created_at, id);
create index if not exists mobile_attachments_sync_idx
  on public.mobile_attachments (tenant, updated_at, id);

